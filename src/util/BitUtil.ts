// Port of org.apache.lucene.util.BitUtil (Lucene 5.2.1).

import { Integer, Long } from "./JavaNumbers.js";

/** table of bits/byte */
const BYTE_COUNTS: Uint8Array = (() => {
  const t = new Uint8Array(256);
  for (let i = 0; i < 256; i++) {
    t[i] = Integer.bitCount(i);
  }
  return t;
})();

// The General Idea: instead of having an array per byte that has
// the offsets of the next set bit, that array could be
// packed inside a 32 bit integer (8 4 bit numbers).  That
// should be faster than accessing an array for each index, and
// the total array size is kept smaller (256*sizeof(int))=1K
//
// The Java source ships this table as a literal that was generated by a
// python script (bits2int). Here the same script is run at load time.
const BIT_LISTS: Int32Array = (() => {
  const t = new Int32Array(256);
  for (let v = 0; v < 256; v++) {
    let arr = 0;
    let val = v;
    for (let shift = 8; shift > 0; shift--) {
      if (val & 0x80) {
        arr = (arr << 4) | shift;
      }
      val = val << 1;
    }
    t[v] = arr;
  }
  return t;
})();

/**
 * A variety of high efficiency bit twiddling routines.
 *
 * Java `long[]` bit sets are represented as `BigInt64Array`; population
 * counts are returned as plain numbers (they never exceed 64 * array length).
 */
export class BitUtil {
  private constructor() {} // no instance

  /**
   * Return the number of bits sets in b.
   * @deprecated Use {@link Integer.bitCount} instead.
   */
  static bitCount(b: number): number {
    return BYTE_COUNTS[b & 0xff]!;
  }

  /**
   * Return the list of bits which are set in b encoded as followed:
   * `(i >>> (4 * n)) & 0x0F` is the offset of the n-th set bit of
   * the given byte plus one, or 0 if there are n or less bits set in the given
   * byte. For example `bitList(12)` returns 0x43.
   * @deprecated do not use.
   */
  static bitList(b: number): number {
    return BIT_LISTS[b & 0xff]!;
  }

  // The pop methods used to rely on bit-manipulation tricks for speed but it
  // turns out that it is faster to use the Long.bitCount method (which is an
  // intrinsic since Java 6u18) in a naive loop, see LUCENE-2221

  /** Returns the number of set bits in an array of longs. */
  static pop_array(arr: BigInt64Array, wordOffset: number, numWords: number): number {
    let popCount = 0;
    for (let i = wordOffset, end = wordOffset + numWords; i < end; ++i) {
      popCount += Long.bitCount(arr[i]!);
    }
    return popCount;
  }

  /**
   * Returns the popcount or cardinality of the two sets after an intersection.
   * Neither array is modified.
   */
  static pop_intersect(arr1: BigInt64Array, arr2: BigInt64Array, wordOffset: number, numWords: number): number {
    let popCount = 0;
    for (let i = wordOffset, end = wordOffset + numWords; i < end; ++i) {
      popCount += Long.bitCount(arr1[i]! & arr2[i]!);
    }
    return popCount;
  }

  /**
   * Returns the popcount or cardinality of the union of two sets.
   * Neither array is modified.
   */
  static pop_union(arr1: BigInt64Array, arr2: BigInt64Array, wordOffset: number, numWords: number): number {
    let popCount = 0;
    for (let i = wordOffset, end = wordOffset + numWords; i < end; ++i) {
      popCount += Long.bitCount(arr1[i]! | arr2[i]!);
    }
    return popCount;
  }

  /**
   * Returns the popcount or cardinality of `A & ~B`.
   * Neither array is modified.
   */
  static pop_andnot(arr1: BigInt64Array, arr2: BigInt64Array, wordOffset: number, numWords: number): number {
    let popCount = 0;
    for (let i = wordOffset, end = wordOffset + numWords; i < end; ++i) {
      popCount += Long.bitCount(arr1[i]! & ~arr2[i]!);
    }
    return popCount;
  }

  /**
   * Returns the popcount or cardinality of A ^ B
   * Neither array is modified.
   */
  static pop_xor(arr1: BigInt64Array, arr2: BigInt64Array, wordOffset: number, numWords: number): number {
    let popCount = 0;
    for (let i = wordOffset, end = wordOffset + numWords; i < end; ++i) {
      popCount += Long.bitCount(arr1[i]! ^ arr2[i]!);
    }
    return popCount;
  }

  /**
   * returns the next highest power of two, or the current value if it's already a power of two or zero.
   * Java overloads for `int` (number) and `long` (bigint).
   */
  static nextHighestPowerOfTwo(v: number): number;
  static nextHighestPowerOfTwo(v: bigint): bigint;
  static nextHighestPowerOfTwo(v: number | bigint): number | bigint {
    if (typeof v === "bigint") {
      v = BigInt.asIntN(64, v - 1n);
      v |= v >> 1n;
      v |= v >> 2n;
      v |= v >> 4n;
      v |= v >> 8n;
      v |= v >> 16n;
      v |= v >> 32n;
      return BigInt.asIntN(64, v + 1n);
    }
    v = (v - 1) | 0;
    v |= v >> 1;
    v |= v >> 2;
    v |= v >> 4;
    v |= v >> 8;
    v |= v >> 16;
    return (v + 1) | 0;
  }

  /**
   * Zig-zag encode the provided int (number) or long (bigint)
   * (https://developers.google.com/protocol-buffers/docs/encoding#types).
   * Assuming the input is a signed value whose absolute value can be stored on
   * n bits, the returned value will be an unsigned value that can be stored on
   * n+1 bits.
   */
  static zigZagEncode(i: number): number;
  static zigZagEncode(l: bigint): bigint;
  static zigZagEncode(x: number | bigint): number | bigint {
    if (typeof x === "bigint") {
      return BigInt.asIntN(64, (x >> 63n) ^ (x << 1n));
    }
    return (x >> 31) ^ (x << 1);
  }

  /** Decode a value previously encoded with {@link BitUtil.zigZagEncode}. */
  static zigZagDecode(i: number): number;
  static zigZagDecode(l: bigint): bigint;
  static zigZagDecode(x: number | bigint): number | bigint {
    if (typeof x === "bigint") {
      return BigInt.asIntN(64, Long.ushr(x, 1) ^ -(x & 1n));
    }
    return (x >>> 1) ^ -(x & 1);
  }
}
